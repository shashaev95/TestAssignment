# -*- coding: utf-8 -*-
"""
Калькулятор маржи инференс-провайдера на примере GLM 5.3 (Sail Research).
Все расчёты в рублях и по СРЕДНИМ значениям рынка.

Запуск:  python glm53_margin_calculator.py

Скрипт запрашивает вводные значения (по Enter — значение по умолчанию)
и считает себестоимость 1 млн токенов, маржу и точку безубыточности.

Дефолты на 22.09.2026:
  - GLM 5.3: 753 млрд параметров, ~40 млрд активных (та же база, что у 5.2);
  - цены Sail (docs.sailresearch.com/pricing): $0.98 вход / $3.08 выход за 1 млн;
  - средняя аренда H200: $3.28 за GPU-час (рынок $2.60–3.95) = 275 руб/час;
  - курс ЦБ РФ: 84,10 руб/$.

Веб-версия с теми же формулами и выгрузкой в PDF — в файле index.html.
"""
import math  # нужен для ceil — округления числа GPU вверх до целого


def ask(prompt, default):
    """Спрашивает у пользователя значение; если нажали Enter — берёт дефолт.

    prompt   — текст вопроса, показывается пользователю;
    default  — значение по умолчанию, если ввод пустой.
    """
    # input() читает строку с клавиатуры; strip() убирает пробелы по краям,
    # replace(",", ".") позволяет вводить десятичные дроби и через запятую ("275,5")
    s = input(f"{prompt} [{default}]: ").strip().replace(",", ".")
    # если пользователь ничего не ввёл — используем default, иначе переводим строку в число
    return float(s) if s else float(default)


# ================== ШАПКА ==================
print("=" * 64)
print("РАСЧЁТ МАРЖИ ИНФЕРЕНСА LLM (всё в рублях) — GLM 5.3")
print("=" * 64)

# ================== 1. ПАРАМЕТРЫ МОДЕЛИ ==================
print("\n--- 1. Параметры модели ---")

# всего параметров в модели, млрд (GLM 5.3 — 753 млрд по данным Hugging Face)
total_params_b = ask("Всего параметров модели, млрд (GLM 5.3 = 753)", 753)
# сколько параметров «просыпается» на каждый токен, млрд (у MoE это ~40 млрд)
active_params_b = ask("Активных параметров на токен, млрд (GLM 5.3 = 40)", 40)
# точность хранения весов: 1 байт = FP8, 2 байта = FP-16
# (FP8 — стандарт для инференса больших MoE: вдвое меньше памяти, качество почти то же)
bytes_per_param = ask("Байт на параметр (FP8 = 1, FP-16 = 2)", 1)
# видеопамять одной GPU, ГБ (H100 = 80, H200 = 141, B200 = 180)
gpu_vram_gb = ask("Память одной GPU, ГБ (H200 = 141)", 141)

# вес модели в ГБ = млрд параметров * байт на параметр
# (753 млрд * 1 байт = 753 ГБ — столько весит GLM 5.3 в FP8)
weights_gb = total_params_b * bytes_per_param
# минимум GPU, чтобы просто разместить веса: делим вес модели на память одной GPU
# и округляем ВВЕРХ (ceil) — 753 / 141 = 5.3 → нужно 6 GPU
gpu_min = math.ceil(weights_gb / gpu_vram_gb)
# узел всегда кратен 8 GPU (стандартная серверная стойка), поэтому округляем до 8
print(f"Веса модели: {weights_gb:.0f} ГБ -> минимум {gpu_min} GPU,"
      f" т.е. нужен узел из {math.ceil(gpu_min / 8) * 8} GPU (кратно 8).")

# ================== 2. ЦЕНА ПРОДАЖИ (ТАРИФ ПРОВАЙДЕРА) ==================
print("\n--- 2. Цена продажи (тариф провайдера) ---")

# курс доллара к рублю для пересчёта тарифов в рубли (ЦБ РФ на 22.09.2026)
usd_rub = ask("Курс доллара, руб", 84.10)
# цена входных токенов (промпт пользователя) за 1 млн, в долларах — прайс Sail
price_in_usd = ask("Цена входных токенов за 1 млн, $ (Sail GLM 5.3 = 0.98)", 0.98)
# цена выходных токенов (ответ модели) за 1 млн, в долларах — прайс Sail
price_out_usd = ask("Цена выходных токенов за 1 млн, $ (Sail GLM 5.3 = 3.08)", 3.08)
# какая доля трафика — входные токены (типично 3 части входа на 1 часть выхода = 0.75)
# (учтите: у Sail есть кэшированный вход за $0.245/1 млн — кэш удешевляет вход,
#  но для базовой оценки маржи без кэша оставляем полную цену)
share_in = ask("Доля входных токенов, 0-1 (типично 0.75)", 0.75)

# переводим цены в рубли за 1 млн токенов
price_in = price_in_usd * usd_rub      # руб за 1 млн входных (0.98 * 84.10 = 82.4 руб)
price_out = price_out_usd * usd_rub    # руб за 1 млн выходных (3.08 * 84.10 = 259.0 руб)
# «бленд» — средневзвешенная цена 1 млн токенов с учётом доли входа/выхода
# пример: 0.75 * 82.4 + 0.25 * 259.0 = 126.6 руб за 1 млн токенов
revenue_1m = share_in * price_in + (1 - share_in) * price_out

# ================== 3. СЕБЕСТОИМОСТЬ (СРЕДНЯЯ АРЕНДА GPU) ==================
print("\n--- 3. Себестоимость (средняя аренда GPU) ---")

# СРЕДНЯЯ стоимость аренды одной GPU в час, в рублях
# (рынок H200: $2.60–3.95 в час; средняя $3.28 * курс 84.10 = ~275 руб/час)
gpu_hour_rub = ask("Средняя аренда одной GPU, руб/час (H200 ~ 275)", 275)
# сколько GPU в одном узле (сервере) — для GLM 5.3 нужен узел из 8 GPU
n_gpu = ask("GPU в узле (GLM 5.3 = 8)", 8)
# АГРЕГИРОВАННАЯ скорость всего узла по всем запросам одновременно, ток/с
# (это не один пользователь! батчинг объединяет десятки запросов;
#  один стрим ~200 ток/с, а узел с батчингом даёт 4000–10000)
throughput = ask("Агрегированная скорость узла, ток/с (батчинг: 4000-10000)", 7000)
# объём трафика для расчёта дневного P&L, млн токенов в день
daily_tokens_mln = ask("Объём трафика, млн токенов в день", 10)

# ================== РАСЧЁТЫ ==================

# стоимость аренды всего узла (8 GPU) за один час, руб (275 * 8 = 2200 руб/час)
node_hour = gpu_hour_rub * n_gpu
# сколько токенов узел генерирует за час при заданной скорости
# (7000 ток/с * 3600 с = 25.2 млн токенов в час)
tokens_per_hour = throughput * 3600
# СЕБЕСТОИМОСТЬ 1 млн токенов = цена часа узла / (сколько миллионов токенов за час)
# пример: 2200 руб/час / 25.2 млн токенов в час = 87.4 руб за 1 млн токенов
cost_1m = node_hour / (tokens_per_hour / 1e6)
# маржа = (выручка - себестоимость) / выручка, в процентах
# пример: (126.6 - 87.4) / 126.6 = +31%
margin = (revenue_1m - cost_1m) / revenue_1m * 100
# точка безубыточности: при какой скорости узла себестоимость сравняется с ценой
# (пример: 2200 * 1e6 / (126.6 * 3600) = ~4830 ток/с; меньше — минус, больше — плюс)
breakeven_thr = node_hour * 1e6 / (revenue_1m * 3600)  # ток/с для нуля

# дневные показатели при заданном объёме трафика
day_cost = daily_tokens_mln / 1 * cost_1m      # себестоимость обслуживания трафика за день
day_rev = daily_tokens_mln / 1 * revenue_1m    # выручка с этого трафика за день

# ================== ВЫВОД РЕЗУЛЬТАТОВ ==================
print("\n" + "=" * 64)
print("РЕЗУЛЬТАТЫ")
print("=" * 64)
# replace(",", " ") — убирает лишние запятые при форматировании тысяч (1 234.5)
print(f"Цена продажи:  вход {price_in:,.1f} руб / выход {price_out:,.1f} руб за 1 млн токенов".replace(",", " "))
print(f"Выручка на 1 млн токенов (бленд): {revenue_1m:,.1f} руб".replace(",", " "))
print(f"Узел: {n_gpu:.0f} GPU x {gpu_hour_rub:,.0f} руб/час = {node_hour:,.0f} руб/час".replace(",", " "))
print(f"Пропускная способность узла: {tokens_per_hour/1e6:,.2f} млн токенов/час".replace(",", " "))
print(f"СЕБЕСТОИМОСТЬ 1 млн токенов:  {cost_1m:,.1f} руб".replace(",", " "))
print(f"МАРЖА: {margin:+.0f}%  ({revenue_1m - cost_1m:+,.1f} руб на 1 млн токенов)".replace(",", " "))
print(f"Точка безубыточности: {breakeven_thr:,.0f} ток/с на узел".replace(",", " "))
print(f"При трафике {daily_tokens_mln:.0f} млн ток/день: выручка {day_rev:,.0f} руб,"
      f" себестоимость {day_cost:,.0f} руб,"
      f" прибыль {day_rev - day_cost:+,.0f} руб/день".replace(",", " "))

# итоговый вердикт по величине маржи (три диапазона)
if margin > 15:
    verdict = "ЗАРАБАТЫВАЮТ: маржа заметно выше нуля при такой утилизации."
elif margin > 0:
    verdict = "ОКОЛО НУЛЯ / небольшой плюс: всё решает утилизация узла."
else:
    verdict = "В МИНУС: при такой загрузке узла продажа убыточна."
print("\nВЫВОД: " + verdict)

# ================== ЧУВСТВИТЕЛЬНОСТЬ ==================
# показываем, как меняется маржа при разной загрузке узла —
# это главная движущая сила экономики инференса
print("\nЧувствительность: себестоимость и маржа при разной скорости узла")
print(f"{'ток/с':>8} | {'себест. руб/1М':>16} | {'маржа':>8}")
for thr in (4000, 5500, 7000, 8500, 10000):          # перебираем сценарии загрузки
    cst = node_hour / (thr * 3600 / 1e6)             # себестоимость 1 млн токенов при этой скорости
    mrg = (revenue_1m - cst) / revenue_1m * 100      # маржа при этой скорости
    print(f"{thr:>8} | {cst:>16,.1f} | {mrg:>7.0f}%".replace(",", " "))
